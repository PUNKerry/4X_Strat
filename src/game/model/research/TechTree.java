    public List<TechNode> getTechs() { return techs; }
    public List<TechNode> getSocials() { return socials; }
    public List<TechNode> getReligions() { return religions; }

    public TechNode getNodeByName(String name) {
        for (TechNode n : techs) if (n.getName().equals(name)) return n;
        for (TechNode n : socials) if (n.getName().equals(name)) return n;
        for (TechNode n : religions) if (n.getName().equals(name)) return n;
        return null;
    }

    public boolean isResearched(String name) {
        TechNode n = getNodeByName(name);
        return n != null && n.isResearched();
    }

    public boolean isReligionUnlocked() {
        return isResearched("Философия");
    }

    public boolean isLegitimacyUnlocked() {
        return isResearched("Вождество"); // изменено с "Империя"
    }

    public boolean isMoneyUnlocked() {
        return isResearched("Стекло");
    }

    public List<TechNode> getAvailableNodes(List<TechNode> branch, TurnManager turnManager) {
        List<TechNode> available = new ArrayList<>();
        for (TechNode node : branch) {
            if (node.isResearched()) continue;
            boolean allPrereqsMet = true;
            for (String prereq : node.getPrerequisites()) {
                if (!isResearched(prereq)) {
                    allPrereqsMet = false;
                    break;
                }
            }
            if (!allPrereqsMet) continue;
            if (branch == socials && turnManager != null) {
                if (!turnManager.isSocialTechAvailable(node)) continue;
            }
            if (branch == religions && !isReligionUnlocked()) continue;
            available.add(node);
        }
        return available;
    }
